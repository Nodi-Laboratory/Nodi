/**
 * 화면 크롬의 기본 배율 (사용자 지시 2026-08-08).
 *
 * 사용자가 브라우저 배율 150%로 쓰고 있었다 — 기본 크기가 작다는 뜻이다.
 * 1.4를 기본으로 삼아, 배율을 올리지 않아도 그만한 크기로 보이게 한다.
 *
 * ## 왜 앱 전체에 `zoom`을 걸지 않았나
 *
 * 제일 쉬운 길은 셸에 `zoom: 1.4` 하나를 거는 것이다. **캔버스가 깨진다** —
 * 실측 2026-08-08: 포트에서 끌어 놓아도 연결이 안 되고, 연결선의 ✕가 실제
 * 자리에서 262px 떨어진 곳에 잡혔다. 캔버스는 `clientX`와 요소 사각형을 섞어
 * 월드 좌표를 푸는데, `zoom`은 그 둘을 서로 다른 방식으로 건드린다.
 *
 * 그래서 **크롬만** 키운다. 사이드바·입력창·도구바·지도 버튼처럼 좌표 계산이
 * 없는 것들이다. 캔버스 안의 글 크기는 학생이 배율로 정하는 값이라 여기서
 * 건드릴 것이 아니다.
 *
 * ## 값은 여기 하나뿐이다
 *
 * CSS는 `--ui-scale` 변수로 읽고, 그 변수를 `app/layout.tsx`가 이 상수로
 * 채운다. CSS에 숫자를 또 적으면 언젠가 둘이 갈린다.
 */
export const UI_SCALE = 1.4;

/** 크롬 치수를 배율에 맞춰 키운다(px). */
export function scaled(px: number): number {
  return Math.round(px * UI_SCALE);
}
