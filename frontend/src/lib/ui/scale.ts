/**
 * 화면 크롬의 기본 배율.
 *
 * ⚠️ **1.4는 노트북 한 대 기준으로 맞춘 값이었다** (2026-08-08). 그 기계에서
 * 브라우저 배율 150%로 쓰고 있다는 이야기를 듣고 앱이 그만큼 커 보이게 한
 * 것인데, **다른 기기에서는 전부 과하게 커졌다.** "지도를 줄여라"·"툴바를
 * 줄여라"·"입력창을 줄여라"가 따로 온 요구처럼 보였지만 원인은 이 값 하나였다
 * (UI 개편 요구사항 2026-08-11).
 *
 * 0.95로 내린다. 실측(미니맵 `MINI`는 `scaled(272×208)`):
 *   1.4  → 381×291px  ← 요구사항이 "화면을 지배하는 큰 창"이라 부른 그것
 *   0.95 → 258×198px  ← 목표(220~260px 폭) 안
 *
 * 1보다 조금 작은 값인 이유는 목표 시안이 우리 기본보다 **살짝 작기** 때문이다.
 * 1.0으로 두면 미니맵이 272px로 목표 상단을 넘고 입력창도 한 단계 크다.
 *
 * ## 왜 앱 전체에 `zoom`을 걸지 않았나
 *
 * 제일 쉬운 길은 셸에 `zoom: 1.4` 하나를 거는 것이다. **캔버스가 깨진다** —
 * 실측 2026-08-08: 포트에서 끌어 놓아도 연결이 안 되고, 연결선의 ✕가 실제
 * 자리에서 262px 떨어진 곳에 잡혔다. 캔버스는 `clientX`와 요소 사각형을 섞어
 * 월드 좌표를 푸는데, `zoom`은 그 둘을 서로 다른 방식으로 건드린다.
 *
 * 그래서 **크롬만** 키운다. 사이드바·입력창·도구바·지도 버튼처럼 좌표 계산이
 * 없는 것들이다. 캔버스 안의 글 크기는 학생이 배율로 정하는 값이라 여기서
 * 건드릴 것이 아니다.
 *
 * ## 값은 여기 하나뿐이다
 *
 * CSS는 `--ui-scale` 변수로 읽고, 그 변수를 `app/layout.tsx`가 이 상수로
 * 채운다. CSS에 숫자를 또 적으면 언젠가 둘이 갈린다.
 */
export const UI_SCALE = 0.95;

/** 크롬 치수를 배율에 맞춰 키운다(px). */
export function scaled(px: number): number {
  return Math.round(px * UI_SCALE);
}
