@dataclass(frozen=True)
class Chunk:
    """RAG 청크 하나 = PDF에 그대로 인쇄되는 소단원 하나."""

    heading: str
    body: str

    @property
    def text(self) -> str:
        # 청크 본문은 제목을 포함한다 — 파서가 만든 청크도 소제목 줄이 딸려 온다.
        return f"{self.heading}\n{self.body}"


@dataclass(frozen=True)
class Page:
    """PDF 한 쪽. 블록은 위에서부터 차례로 인쇄된다."""

    #: 쪽 맨 위의 큰 제목(없으면 생략).
    title: str | None = None
    #: 본문 앞의 안내 문단(청크 아님 — 표지·목차용).
    lead: list[str] = field(default_factory=list)
    chunks: list[Chunk] = field(default_factory=list)
    #: 이 쪽에 실리는 도판 키. 청크 뒤에 인쇄된다.
    figures: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class DemoFile:
    key: str
    name: str  # 화면에 보이는 이름(한국어)
    storage_name: str  # 저장소 키는 ASCII(files.py 규약)
    kind: str  # class_material | textbook
    header: str  # PDF 쪽 머리글
    pages: list[Page]
    uploaded_days_ago: int

    @property
    def id(self) -> str:
        return uid(f"file:{self.key}")

    def chunks(self) -> list[Chunk]:
        return [c for p in self.pages for c in p.chunks]


def chunk_id(file_key: str, seq: int) -> str:
    return uid(f"chunk:{file_key}:{seq}")


