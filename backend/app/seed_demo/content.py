def figure_pages() -> dict[str, int]:
    """도판 키 → 교과서 쪽 번호(1부터)."""
    out: dict[str, int] = {}
    for i, page in enumerate(TEXTBOOK.pages, start=1):
        for fk in page.figures:
            out[fk] = i
    return out


def page_text(file: DemoFile, page_no: int) -> str:
    """도판 캡션 생성에 쓰였을 페이지 본문(D131 `page_text`)."""
    page = file.pages[page_no - 1]
    parts = ([page.title] if page.title else []) + list(page.lead)
    parts += [c.text for c in page.chunks]
    return "\n".join(parts)


def figure_heading(fig_key: str) -> str:
    page = TEXTBOOK.pages[figure_pages()[fig_key] - 1]
    if page.chunks:
        return page.chunks[0].heading
    return page.title or ""


