def clip_ref(ref: str) -> tuple[Video, Clip]:
    """'video:clip' 참조 → (영상, 클립)."""
    vkey, ckey = ref.split(":")
    video = VIDEO_BY_KEY[vkey]
    clip = next(c for c in video.clips if c.key == ckey)
    return video, clip


