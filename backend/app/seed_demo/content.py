# 답 원문 → 캔버스 카드 (프론트 streamParser와 같은 규칙)
# ---------------------------------------------------------------------------
def card_from_answer(answer: str) -> tuple[str | None, str | None, str]:
    """답 원문에서 (제목, 분류, 본문)을 뽑는다.

    화면(`lib/canvas2/streamParser.ts` + `useCanvasStream.ts`)이 카드를 만드는
    규칙을 그대로 따른다:

      · `@concept: 제목 | 분류` 다음 줄부터 `@end` 전까지가 본문
      · 본문 맨 앞의 빈 줄은 버리고, 문단 사이 빈 줄은 **그대로 둔다**
      · `@related:` 줄은 본문에 넣지 않는다
      · 한 턴에 카드 하나(cardsPerTurn=1) — 두 번째 개념부터는 `**제목**` 줄과
        함께 앞 카드에 이어 붙인다

    이 시드의 답은 전부 개념 하나짜리라 마지막 규칙은 보험이다.
    """
    title: str | None = None
    tag: str | None = None
    lines: list[str] = []
    in_concept = False
    body_empty = True
    for raw in answer.splitlines():
        line = raw.strip()
        if line.startswith("CHAT:"):
            continue
        if line.startswith("@concept:"):
            parts = [p.strip() for p in line[len("@concept:"):].split("|")]
            if title is None:
                title = parts[0] or None
                tag = (parts[1] if len(parts) > 1 else "") or None
            else:
                lines.append(f"**{parts[0]}**")
            in_concept = True
            body_empty = True
            continue
        if line == "@end":
            in_concept = False
            continue
        if line.startswith("@related:"):
            continue
        if not in_concept:
            continue
        if body_empty and not line:
            continue
        body_empty = False
        lines.append(line)
    return title, tag, "\n".join(lines).rstrip()
