-- 홈 지도 떠다니는 세기를 낮춘다 (사용자 지시 2026-08-11)
--
-- 상자를 걷어내며 지도가 화면 전체로 넓어졌다. `FIT_BOOST`가 그 넓이에 맞춰
-- 배율을 올리므로 **같은 힘이 더 많은 픽셀을 움직인다** — 세기는 그대로인데
-- 화면에서는 세 보인다. 실측(250ms 사이 변한 픽셀, 12회 평균):
--
--   상자 있던 때  force 0.30 →  4.5%
--   상자 걷은 뒤  force 0.30 → 23.2%   ← 사용자 지적 "움직이는 게 심하다"
--                 force 0.08 →  약 5%   ← 예전에 적당하다던 그 수준
--
-- ⚠️ 튜너블은 `app_settings` 행이 config 기본값을 이긴다(D62). 코드만 고치면
-- 이미 돌고 있는 DB에서는 **아무 일도 안 일어난다** — 그래서 행도 옮긴다.
--
-- ⚠️ **관리자가 일부러 바꾼 값은 안 건드린다.** 옛 기본값(0.3)인 행만 옮긴다.
-- 멱등이다 — 여러 번 돌려도 같다.

UPDATE public.app_settings
   SET value = '0.08'
 WHERE key = 'home_drift_force'
   AND value IN ('0.3', '0.30');
