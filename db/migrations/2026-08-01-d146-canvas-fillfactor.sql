-- D146: 자주 고쳐 쓰는 표에 페이지 여유를 남긴다(fillfactor).
--
-- ## 무엇이 문제였나
--
-- `canvas_items`는 **드래그 한 번이 UPDATE 한 번**인 표다. 재배치 버튼은 수십
-- 행을 한꺼번에 고친다. 그런데 실측해 보니 갱신 12,242번 중 HOT 갱신이
-- 324번(2.6%)뿐이었다.
--
-- HOT(Heap-Only Tuple)은 **인덱스를 건드리지 않는 갱신**이다. 두 조건이 맞아야
-- 한다: (1) 인덱스에 걸린 열이 안 바뀌고, (2) 같은 페이지에 새 버전을 쓸 자리가
-- 있을 것. 이 표의 인덱스는 id·(session_id,seq,created_at)·parent_item_id·
-- node_id뿐이라 x/y를 고치는 드래그는 (1)을 만족한다. 막고 있던 것은 (2),
-- 즉 **페이지가 꽉 차 있었다는 것**이다(fillfactor 기본값 100).
--
-- HOT이 안 되면 갱신마다 인덱스 4개에 새 항목이 생기고, 표와 인덱스가 함께
-- 부푼다.
--
-- ## 실측 (같은 부하: 2,000행 × 갱신 10,000회)
--
--     fillfactor 100   HOT  1.7%   크기 2,808 kB   ← 지금
--     fillfactor  90   HOT 28.7%   크기 2,136 kB
--     fillfactor  85   HOT 44.0%   크기 1,944 kB
--     fillfactor  80   HOT 56.7%   크기 1,752 kB   ← 채택
--     fillfactor  75   HOT 65.5%   크기 1,648 kB
--     fillfactor  70   HOT 76.8%   크기 1,472 kB
--
-- 낮출수록 좋아 보이지만 공짜가 아니다. 갱신이 없는 표는 그만큼 페이지가
-- 늘어 **읽을 때 더 많은 페이지를 훑는다.** 캔버스는 열 때마다 세션의 글을
-- 전부 읽으므로 읽기도 중요하다. 그래서 갱신의 절반 이상을 HOT으로 돌리면서
-- 밀도는 20%만 양보하는 80을 골랐다.
--
-- ## 이미 있는 페이지는?
--
-- fillfactor는 **새로 쓰는 페이지**에만 적용된다. 기존 페이지는 죽은 튜플이
-- 청소되면서 자연히 여유가 생긴다. 여기서 `VACUUM FULL`을 하지 않는 이유는
-- 이 마이그레이션이 배포마다 다시 돌기 때문이다 — 매번 ACCESS EXCLUSIVE 잠금을
-- 걸어 표를 통째로 다시 쓰는 것은 배포가 할 일이 아니다.
--
-- `sessions`·`jobs`는 일부러 두었다. 저쪽은 갱신하는 열(updated_at·status)이
-- **인덱스에 들어 있어** 조건 (1)이 깨진다 — fillfactor를 낮춰도 HOT이 안 된다.
--
-- 멱등: 같은 값을 다시 설정하는 것은 아무 일도 하지 않는다.

ALTER TABLE public.canvas_items SET (fillfactor = 80);

-- 그림은 획 하나마다 장면 전체를 다시 쓴다. 본문은 TOAST로 빠지지만 행 자체도
-- 자주 갱신되므로 조금 여유를 준다.
ALTER TABLE public.canvas_drawings SET (fillfactor = 85);
